#: 띄어쓰기와 가운뎃점이 제각각이다. 「운영 규정」과 「운영규정」이 같이 온다.
_NOISE = re.compile(r"[\s·ㆍ‧・]")


def _normalize(title: str) -> str:
    """공백과 가운뎃점을 지운다. 「운영 규정」과 「운영규정」을 같게 본다."""
    return _NOISE.sub("", title)


#: 표를 정규화해 둔다.
#:
#: 제목만 정규화하고 표는 그대로 뒀더니 「경고ㆍ주의」 가 새 나갔다.
#: 제목 쪽에서 가운뎃점이 지워지므로 표에도 없어야 만난다. 양쪽에
#: 같은 처리를 하지 않으면 규칙이 조용히 반쪽만 돈다.
_TAXPAYER = tuple(_normalize(m) for m in TAXPAYER_MARKERS)
_INTERNAL = tuple(_normalize(m) for m in INTERNAL_MARKERS)


def is_internal_rule(title: str) -> bool:
    """부처 내부 운영 규칙인가 — 담지 않아도 되는가.

    납세자에게 걸리는 말이 하나라도 있으면 내부 규칙으로 보지 않는다.
    「재정경제부 소관 법령에 따른 행정처분 및 과태료의 가중처분에 관한
    세부지침」은 감사와 무관하지만 "과태료" 때문에 남는다 — 그게 맞다.
    """
    text = _normalize(title)
    if any(marker in text for marker in _TAXPAYER):
        return False
    return any(marker in text for marker in _INTERNAL)


