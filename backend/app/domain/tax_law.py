"""법령 이름이 세법인가.

입법예고와 의안은 제목이 곧 법령 이름이다. 「부가가치세법 일부개정법률안
입법예고」처럼 무엇에 관한 것인지 제목에 다 들어 있다. 그래서 여기서는
본문을 읽지 않고 이름만 본다.

**소관부처로 거르려던 계획은 틀렸다.**

수집기를 만들 때 국세청(1210000)과 기획재정부(1051000) 코드로 서버에서
거르려 했다. 그런데 실제로 불러 보니 두 부처 다 0건이었다. 정부조직이
바뀌어 지금 세법을 내는 곳은 **재정경제부**다.

그리고 부처로 걸러도 답이 안 나온다. 재정경제부가 낸 19건에는 이런 것이
섞여 있다.

    국가를 당사자로 하는 계약에 관한 법률 시행령 일부개정령안
    국유재산특례제한법 일부개정법률안
    경제안보를 위한 공급망 안정화 지원 기본법 시행령 일부개정령안

세법이 아니다. 반대로 행정안전부 11건에는 지방세가 하나도 없었다.
부처는 세법의 경계와 맞지 않는다.

**세목 이름으로 거른다.** 제목이 법령 이름이므로 이 경우엔 이름이 곧
내용이다 — 행정규칙에서 낱말 필터가 실패한 것(「국세청 인사관리규정」)과
사정이 다르다. 거기서는 제목이 부서 업무였고 여기서는 법령이다.
"""

from __future__ import annotations

import re

#: 세목과 세법 이름. 국세·지방세·관세를 모두 넣는다.
#:
#: 사장님에게는 국세든 지방세든 같은 고지서다. 어느 쪽인지는 우리가
#: 나눌 일이지 안 담을 이유가 아니다.
TAX_MARKERS: tuple[str, ...] = (
    # 국세
    "소득세",
    "법인세",
    "부가가치세",
    "상속세",
    "증여세",
    "종합부동산세",
    "개별소비세",
    "교통에너지환경세",
    "주세법",
    "인지세",
    "증권거래세",
    "교육세",
    "농어촌특별세",
    "국세기본",
    "국세징수",
    "조세특례",
    "국제조세",
    "조세범",
    "조세",
    # 지방세
    "지방세",
    "취득세",
    "등록면허세",
    "재산세",
    "주민세",
    "자동차세",
    "담배소비세",
    "레저세",
    "지역자원시설세",
    "지방소득세",
    "지방소비세",
    # 관세
    "관세",
    # 신고·납세 실무
    "세무사법",
    "성실신고",
    "가산세",
    "세액공제",
    "부가세",
)

#: 세목이 들어 있어도 세법이 아닌 것.
#:
#: 「관세청과 그 소속기관 직제 시행규칙」은 "관세" 가 있지만 관세청의
#: 조직도다. 사장님이 낼 세금과 아무 상관이 없다. 행정규칙에서
#: 「국세청 인사관리규정」을 걸러 낸 것과 같은 이유다.
ORGANISATION_MARKERS: tuple[str, ...] = (
    "직제",
    "소속기관",
    "정원",
    "공무원수당",
    "사무분장",
    "위임전결",
)

_NOISE = re.compile(r"[\s·ㆍ‧・]")


def _normalize(name: str) -> str:
    """공백과 가운뎃점을 지운다. 「상속세 및 증여세법」과 붙여 쓴 것을 같게 본다."""
    return _NOISE.sub("", name)


_TAX = tuple(_normalize(m) for m in TAX_MARKERS)
_ORG = tuple(_normalize(m) for m in ORGANISATION_MARKERS)


def is_tax_law(name: str) -> bool:
    """이 법령 이름이 세법인가.

    조직·정원 규정이면 세목이 들어 있어도 아니다.
    """
    text = _normalize(name)
    if any(marker in text for marker in _ORG):
        return False
    return any(marker in text for marker in _TAX)


__all__ = ["ORGANISATION_MARKERS", "TAX_MARKERS", "is_tax_law"]
